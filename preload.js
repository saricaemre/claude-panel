  // Kanca günlüğü (hooks.js): sohbetin aldığı Claude Code kanca olayları
  hooksLog: (chatId) => ipcRenderer.invoke('hooks:log', chatId),
  widgetRegister: (code) => ipcRenderer.invoke('widget:register', code),
